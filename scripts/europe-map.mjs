// Builds src/travel/europeMap.ts: a Mercator basemap of Europe as SVG paths,
// with visited countries split out so they can be shaded. Run with `npm run map`.
// The projection constants are exported so city pins can be placed at runtime.
import { geoMercator, geoPath } from 'd3-geo'
import { feature } from 'topojson-client'
import { presimplify, simplify } from 'topojson-simplify'
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const target = resolve(here, '../src/travel/europeMap.ts')

// ISO 3166 numeric codes: Spain, UK, France, Switzerland, Denmark, Ireland,
// Hungary, Italy, Greece, Austria.
const VISITED = new Set(['724', '826', '250', '756', '208', '372', '348', '380', '300', '040'])

const WIDTH = 800
const HEIGHT = 560
// Map window in degrees: west, south, east, north.
const BOUNDS = [-11.5, 34.2, 28.5, 59]

const topo = JSON.parse(readFileSync(resolve(here, '../node_modules/world-atlas/countries-50m.json'), 'utf8'))
// Drop detail smaller than the map can show. Weight is in squared degrees.
const simple = simplify(presimplify(topo), 0.003)
const countries = feature(simple, simple.objects.countries).features

const frame = {
  type: 'Feature',
  geometry: {
    type: 'MultiPoint',
    coordinates: [
      [BOUNDS[0], BOUNDS[1]],
      [BOUNDS[2], BOUNDS[3]],
    ],
  },
}
const projection = geoMercator()
  .fitSize([WIDTH, HEIGHT], frame)
  .clipExtent([
    [-20, -20],
    [WIDTH + 20, HEIGHT + 20],
  ])
const path = geoPath(projection).digits(1)

const visited = []
const other = []
for (const c of countries) {
  const d = path(c)
  if (!d) continue
  ;(VISITED.has(String(c.id)) ? visited : other).push(d)
}

const [tx, ty] = projection.translate()
const out = `// Generated by scripts/europe-map.mjs. Do not edit by hand.
export const MAP_WIDTH = ${WIDTH}
export const MAP_HEIGHT = ${HEIGHT}
export const visitedPath = ${JSON.stringify(visited.join(''))}
export const otherPath = ${JSON.stringify(other.join(''))}

const SCALE = ${projection.scale()}
const TX = ${tx}
const TY = ${ty}

/** Same Mercator projection the basemap was drawn with. */
export function project(lat: number, lon: number): [number, number] {
  const x = (lon * Math.PI) / 180
  const y = Math.log(Math.tan(Math.PI / 4 + (lat * Math.PI) / 360))
  return [TX + SCALE * x, TY - SCALE * y]
}
`
mkdirSync(dirname(target), { recursive: true })
writeFileSync(target, out)
console.log(`Wrote ${target} (${(out.length / 1024).toFixed(1)} KB)`)
